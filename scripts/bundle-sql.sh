#!/usr/bin/env bash
# Concatenates all migrations into supabase/setup.sql for pasting into the Supabase SQL Editor.
set -euo pipefail
cd "$(dirname "$0")/.."
out=supabase/setup.sql
{
  echo "-- GENERATED by scripts/bundle-sql.sh. Do not edit; edit supabase/migrations instead."
  echo "-- Paste into Supabase Dashboard > SQL Editor and run once on a NEW, empty project."
  for f in supabase/migrations/*.sql; do
    echo
    echo "-- ===== $(basename "$f") ====="
    cat "$f"
  done
} > "$out"
echo "Wrote $out"
